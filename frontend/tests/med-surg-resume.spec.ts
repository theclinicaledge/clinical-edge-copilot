import { test, expect } from '@playwright/test';
import { seedTrack } from './med-surg-fixtures.mjs';
const key = 'ce-med-surg-track-private';
async function prepare(page, seed = null, id = 'a1') {
  await page.route('**/*', route => {
    const request = route.request(), url = new URL(request.url());
    return url.hostname === '127.0.0.1' && request.method() === 'GET' && !url.pathname.startsWith('/api/') ? route.continue() : route.fulfill({ body: '', contentType: 'text/css' });
  });
  if (seed) await page.addInitScript(({ seed, key }) => { if (!localStorage.getItem(key)) localStorage.setItem(key, JSON.stringify(seed)); }, { seed, key });
  await page.goto('/learn/med-surg/' + id);
  await expect(page.locator('.mst-session')).toBeVisible();
  await page.getByRole('link', { name: 'Skip to assignment' }).focus();
  await page.keyboard.press('Enter');
  await expect(page.locator('#mst-main')).toBeFocused();
}
test('A1 refresh retains original priority, partial cue draft and assisted wrong action', async ({ page }) => {
  await prepare(page);
  await page.getByRole('button', { name: 'Plan your first assessment' }).click();
  await page.getByRole('button', { name: 'Assess Room 14' }).click();
  await page.reload();
  let run = await page.evaluate(key => JSON.parse(localStorage.getItem(key)!).assignments.a1.runs[0], key);
  expect(run.snapshot.answers.priority).toBe('14');
  await expect(page.getByRole('button', { name: 'Assess Room 12' })).toBeDisabled();
  await page.getByRole('button', { name: 'Go to Room 12' }).click();
  await page.getByRole('button', { name: /^Oxygen saturation/ }).click();
  const cue = page.locator('.shift-cue').filter({ hasText: 'SpO2 97% on nasal cannula' }).getByRole('checkbox');
  await cue.check(); await page.reload();
  await expect(cue).toBeChecked();
  await page.getByRole('button', { name: 'Confirm 1 cue' }).click(); await page.reload();
  await expect(cue).toBeDisabled();
  await page.getByRole('button', { name: 'Decide what to do now' }).click();
  await page.getByRole('button', { name: /^Wait for the ABG drawn/ }).click(); await page.reload();
  run = await page.evaluate(key => JSON.parse(localStorage.getItem(key)!).assignments.a1.runs[0], key);
  expect(run.snapshot.answers.action).toBe('wait');
  expect(run.decisions.action.value).toBe('wait');
  expect(run.decisions.action.independent).toBe(false);
  expect(run.decisions.cues.value).toEqual(['saturation']);
  expect(run.decisions.cues.independent).toBe(false);
  expect(await page.evaluate(() => localStorage.getItem('ce-private-shift-drowsy-r2'))).toBeNull();
});
test('A2 refresh retains drafts, original dispatch and bridge assistance on later choices', async ({ page }) => {
  await prepare(page, seedTrack({ a2Complete: false }), 'a2');
  await page.getByRole('button', { name: 'Plan my round' }).click();
  for (const room of ['412', '414', '410', '416']) await page.locator('.s5-round-rooms').getByRole('button').filter({ hasText: 'ROOM ' + room }).click();
  await page.getByRole('button', { name: 'Something time-sensitive is due', exact: true }).click(); await page.reload();
  await expect(page.getByRole('button', { name: 'Set my plan' })).toBeEnabled();
  await page.getByRole('button', { name: 'Set my plan' }).click();
  await page.getByRole('button', { name: 'Continue shift', exact: true }).click();
  const room = id => page.locator('.s5-dispatch').filter({ hasText: 'ROOM ' + id });
  await room('412').getByRole('button', { name: 'You', exact: true }).click();
  await room('410').getByRole('button', { name: 'Jordan', exact: true }).click();
  await room('410').getByRole('button', { name: 'Can you help 410 to the bathroom?', exact: true }).click();
  await page.reload();
  let run = await page.evaluate(key => JSON.parse(localStorage.getItem(key)!).assignments.a2.runs[0], key);
  expect(run.snapshot.d2Draft.assignments['412']).toBe('you');
  expect(run.snapshot.d2Draft.jordanDirection).toBe('B');
  await room('416').getByRole('button', { name: 'Hold / Sam', exact: true }).click();
  await room('416').getByRole('button', { name: /Your nurse knows your ride/ }).click();
  await page.getByRole('button', { name: 'Send assignments' }).click(); await page.reload();
  run = await page.evaluate(key => JSON.parse(localStorage.getItem(key)!).assignments.a2.runs[0], key);
  expect(run.snapshot.d2.submitted.jordanDirection).toBe('B');
  expect(run.snapshot.d2.bridges.length).toBe(1);
  expect(run.snapshot.d2.storyPlan).toBe('V1');
  await page.getByRole('button', { name: 'Follow the shift' }).click();
  await page.getByRole('button', { name: 'Continue to 0730' }).click();
  await page.getByRole('button', { name: /^A\. Dee/ }).click();
  await page.getByRole('button', { name: 'Send handoff' }).click(); await page.reload();
  run = await page.evaluate(key => JSON.parse(localStorage.getItem(key)!).assignments.a2.runs[0], key);
  expect(run.decisions.d3.label).toBe('Accepted');
  expect(run.decisions.d3.independent).toBe(false);
  expect(run.decisions.d3.assistance).toContain('D2 safer-path bridge');
  expect(run.snapshot.d2.submitted.jordanDirection).toBe('B');
  expect(await page.evaluate(() => localStorage.getItem('ce_shift_005_v04'))).toBeNull();
});
